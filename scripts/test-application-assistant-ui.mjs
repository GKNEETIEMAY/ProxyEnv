import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
const require = createRequire(process.env.PROXYENV_LAYOUT_PLAYWRIGHT || import.meta.url);
const { chromium } = require("playwright");
const browser = await chromium.launch({ headless: true, ...(process.env.PROXYENV_LAYOUT_BROWSER ? { executablePath: process.env.PROXYENV_LAYOUT_BROWSER } : {}) });
const output = resolve('.impeccable/review/local-v0.2.2');
mkdirSync(output, { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 880, height: 760 }, reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${process.env.PROXYENV_LAYOUT_URL || 'http://127.0.0.1:1422'}/scripts/fixtures/application-assistant.html`, { waitUntil: 'domcontentloaded' });
  await page.locator('.application-list button').first().waitFor();
  for (const locale of ['zh-CN','en','ja','ko']) for (const width of [560,880]) {
    await page.setViewportSize({ width, height: 760 });
    await page.evaluate(locale => fixture.state.locale = locale, locale);
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(resolve)));
    assert.equal(await page.locator('.application-picker-actions').evaluate(node => node.scrollWidth > node.clientWidth), false, `${locale}/${width}: search toolbar overflow`);
  }
  await page.setViewportSize({ width: 880, height: 760 });
  await page.evaluate(() => fixture.state.locale = 'zh-CN');
  const searchBounds = await page.locator('input[type=search]').boundingBox();
  const refreshBounds = await page.locator('.application-picker-actions > button').first().boundingBox();
  assert.ok(searchBounds.x + searchBounds.width <= refreshBounds.x && Math.abs(searchBounds.y - refreshBounds.y) < 5, 'Search is directly before Refresh in the same toolbar');
  if (process.argv.includes('--screenshots')) await page.screenshot({ path: resolve(output, 'assistant-search.png') });
  assert.match(await page.locator('.assistant-steps').innerText(), /选择应用.*查看配置.*验证效果/s);
  await page.locator('input[type=search]').fill('code');
  assert.equal(await page.locator('.application-list button').count(), 1);
  await page.locator('input[type=search]').fill('missing');
  assert.match(await page.locator('.assistant-empty').innerText(), /未找到匹配/);
  assert.equal(await page.evaluate(() => fixture.calls.some(([c]) => c.startsWith('launch_') || c === 'diagnose_application')), false);
  await page.locator('input[type=search]').fill('C:\\Apps\\Code');
  if (process.argv.includes('--screenshots')) await page.screenshot({ path: resolve(output, 'assistant-picker.png') });
  await page.locator('.application-list button').click();
  await page.locator('.diagnosis-hero').waitFor();
  assert.match(await page.locator('.assistant-active-proxy').innerText(), /\[::1\]:10808/);
  assert.equal(await page.locator('.assistant-other-actions button').first().isVisible(), false);
  assert.equal(await page.evaluate(() => fixture.calls.some(([c]) => c.startsWith('launch_'))), false, 'Inspection does not launch');
  if (process.argv.includes('--screenshots')) await page.screenshot({ path: resolve(output, 'assistant-diagnosis.png'), fullPage: true });
  await page.locator('.assistant-action-panel .primary-action').click();
  await page.locator('.result-panel').waitFor();
  assert.match(await page.locator('.result-panel').innerText(), /启动成功不代表联网成功/);
  assert.deepEqual(await page.evaluate(() => fixture.calls.filter(([c]) => c.startsWith('launch_'))), [['launch_application_with_current_proxy', { applicationId: 'code', expectedRevision: 1 }]]);
  await page.locator('.result-panel > button').click();
  await page.locator('.diagnosis-hero').waitFor();
  assert.equal(await page.evaluate(() => fixture.calls.filter(([c]) => c === 'diagnose_application').length), 2);
  await page.locator('.assistant-other-actions summary').click();
  assert.match(await page.locator('.assistant-other-actions').innerText(), /Windows 系统代理和 TUN/);
  await page.locator('.assistant-other-actions button').first().click();
  await page.locator('dialog[open]').waitFor();
  assert.match(await page.locator('dialog[open]').innerText(), /HTTP \/ SOCKS5/);
  await page.keyboard.press('Escape');
  await page.locator('.assistant-other-actions button').last().click();
  await page.locator('.result-panel').waitFor();
  assert.match(await page.locator('.result-panel h2').innerText(), /不带代理环境变量/);
  await page.locator('.result-panel > button').click();
  await page.locator('.diagnosis-hero').waitFor();
  await page.evaluate(() => { fixture.state.diagnosisState='ruleSyncRecommended'; fixture.state.action={ applyKnownRule: 'test' }; fixture.state.active.revision++; });
  await page.getByRole('button', { name: '预览一键修复', exact: true }).click();
  await page.locator('.rule-confirmation').waitFor();
  assert.equal(await page.evaluate(() => fixture.calls.some(([c]) => c === 'apply_application_rule_fix')), false, 'Rule preview never writes');
  await page.locator('.rule-confirmation .primary-action').click();
  await page.locator('.result-panel').waitFor();
  await page.locator('.result-panel > button').click();
  await page.locator('.assistant-restore > button').waitFor();
  await page.locator('.assistant-restore > button').click();
  await page.locator('.assistant-restore .primary-action').click();
  await page.locator('.result-panel').waitFor();
  assert.deepEqual(await page.evaluate(() => fixture.calls.find(([c]) => c === 'restore_application_rule_change')), ['restore_application_rule_change', { backupId: 'backup', confirmed: true }], 'Rechecking retains the ability to restore the saved change');
  await page.locator('.result-panel > button').click();
  await page.locator('.diagnosis-hero').waitFor();
  await page.evaluate(() => { fixture.state.diagnosisState='confirmedReady'; fixture.state.action='none'; fixture.state.active.revision++; });
  await page.waitForFunction(() => !document.querySelector('.assistant-loading-panel') && !document.querySelector('.assistant-action-panel .primary-action'));
  assert.equal(await page.locator('.assistant-action-panel .primary-action').count(), 0, 'A configuration requiring no action does not promote another launch');
  for (const locale of ['zh-CN','en','ja','ko']) for (const width of [560,880]) for (const mode of ['light','dark']) {
    await page.setViewportSize({ width, height: 760 });
    await page.evaluate(({ locale, mode }) => { fixture.state.locale = locale; fixture.theme('blue', mode); }, { locale, mode });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${locale}/${width}/${mode}: overflow`);
  }
  await page.evaluate(() => { fixture.state.locale='zh-CN'; fixture.state.active.available=false; fixture.state.active.revision++; });
  await page.locator('.assistant-active-proxy button').waitFor();
  assert.equal(await page.locator('.assistant-action-panel .primary-action').count(), 0, 'No proxy launch for unavailable selection');
  await page.locator('.assistant-active-proxy button').click();
  assert.equal(await page.evaluate(() => fixture.state.back), true);
  assert.equal(await page.evaluate(() => fixture.calls.some(([c]) => c.includes('test_current') || c.includes('sync_proxy'))), false, 'App inspection never silently tests or writes the environment');
  assert.deepEqual(errors, []);
  console.log('Application assistant passed: search, inspection, explicit launch, recheck, manual protocol guidance, unavailable recovery; 16 locale/width/theme cases. Synthetic IPC only.');
} finally { await browser.close(); }
